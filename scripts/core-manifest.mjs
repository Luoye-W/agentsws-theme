// Upstream maintainers only: records hashes of core theme files so store repos can detect edits.
//   npm run core:manifest                    write scripts/core-manifest.json
//   node scripts/core-manifest.mjs --check   exit 1 when it is stale (run by `npm run verify` in the upstream repo)
import { writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { ROOT, read, list, originOf, loadJSON, PROTECTED_DIRS } from './lib.mjs';

const files = {};
for (const rel of PROTECTED_DIRS.flatMap((d) => list(d))) {
  if (originOf(rel) !== 'core') continue;
  if (rel.startsWith('templates/') || rel.startsWith('locales/') || rel.startsWith('config/settings_data') || /^sections\/.*\.json$/.test(rel) || rel === 'assets/app.css') continue;
  files[rel] = createHash('sha256').update(read(rel)).digest('hex');
}
const out = { $comment: 'GENERATED by `npm run core:manifest` (upstream release step).', version: loadJSON('package.json').version, files };
const text = `${JSON.stringify(out, null, 2)}\n`;
if (process.argv.includes('--check')) {
  const current = existsSync(join(ROOT, 'scripts/core-manifest.json')) ? read('scripts/core-manifest.json') : '';
  if (current === text) process.exit(0);
  const recorded = current ? JSON.parse(current).files ?? {} : {};
  const changed = Object.keys({ ...recorded, ...files }).filter((rel) => recorded[rel] !== files[rel]);
  console.log(`scripts/core-manifest.json is stale (${changed.length} core files differ, e.g. ${changed.slice(0, 5).join(', ') || 'version'}).`);
  process.exit(1);
}
writeFileSync(join(ROOT, 'scripts/core-manifest.json'), text);
console.log(`Recorded ${Object.keys(files).length} core files.`);
