// Upstream maintainers only: records hashes of core theme files so store repos can detect edits.
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { ROOT, read, list, originOf, loadJSON, PROTECTED_DIRS } from './lib.mjs';

const files = {};
for (const rel of PROTECTED_DIRS.flatMap((d) => list(d))) {
  if (originOf(rel) !== 'core') continue;
  if (rel.startsWith('templates/') || rel.startsWith('locales/') || rel.startsWith('config/settings_data') || /^sections\/.*\.json$/.test(rel) || rel === 'assets/app.css') continue;
  files[rel] = createHash('sha256').update(read(rel)).digest('hex');
}
const out = { $comment: 'GENERATED by `npm run core:manifest` (upstream release step).', version: loadJSON('package.json').version, files };
writeFileSync(join(ROOT, 'scripts/core-manifest.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`Recorded ${Object.keys(files).length} core files.`);
